type Widen<T> = T extends string
  ? string
  : T extends Readonly<Record<string, infer V>>
    ? string extends keyof T
      ? Readonly<Record<string, V>>
      : { readonly [K in keyof T]: Widen<T[K]> }
    : T;

/** The shape every language catalog must have. */
